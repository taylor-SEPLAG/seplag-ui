// @vitest-environment jsdom
import { afterEach, expect, it } from "vitest";
import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import { PesosAbrangenciasContent } from "./PesosAbrangenciasContent";
import { MemoryRouter } from "react-router-dom";

afterEach(() => { cleanup(); localStorage.clear(); });
const chave = "sigep:pesos-abrangencias:v1";
it("pagina as versões e retorna ao início ao limpar os filtros", () => {
  localStorage.setItem(chave, JSON.stringify(Array.from({ length: 12 }, (_, i) => ({ numero: 12 - i, inicio: "2026-11-16T12:00:00Z", fim: i ? "2026-11-16T13:00:00Z" : null, pesos: [100, 40, 30, 20, 10, 0] }))));
  render(<MemoryRouter><PesosAbrangenciasContent /></MemoryRouter>);
  expect(screen.getAllByRole("columnheader").map(campo => campo.textContent)).toEqual(["Versão", "Situação", "Ações"]);
  expect(screen.getAllByRole("button", { name: "Visualizar" })).toHaveLength(10);
  fireEvent.click(document.querySelector(".p-paginator-next")!);
  expect(screen.getAllByRole("button", { name: "Visualizar" })).toHaveLength(2);
  expect(screen.getByRole("cell", { name: "V1" })).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "Limpar filtros" }));
  expect(screen.getAllByRole("button", { name: "Visualizar" })).toHaveLength(10);
  expect(screen.getByRole("cell", { name: "V12" })).toBeTruthy();
});
it("aprova a primeira versão, impede duplicação e preserva os pesos históricos", () => {
  render(<MemoryRouter><PesosAbrangenciasContent /></MemoryRouter>);
  fireEvent.click(screen.getByRole("button", { name: "Nova parametrização" }));
  expect((screen.getByLabelText("Órgão/Entidade") as HTMLInputElement).value).toBe("100");
  expect(screen.queryByRole("region", { name: "Vigência" })).toBeNull();
  fireEvent.click(screen.getByRole("button", { name: "Aprovar parametrização" }));
  expect(localStorage.getItem(chave)).toBeNull();
  fireEvent.click(screen.getByRole("button", { name: "Confirmar aprovação" }));
  expect(JSON.parse(localStorage.getItem(chave)!)).toHaveLength(1);
  fireEvent.click(screen.getByRole("button", { name: "Nova versão a partir de V1" }));
  expect(screen.getByRole("heading", { name: "Versionar Parametrização de Pesos" })).toBeTruthy();
  expect(screen.getByText("Versão atual: V1")).toBeTruthy();
  expect(screen.getByText("Nova versão: V2")).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "Aprovar nova versão" }));
  expect(screen.getByRole("alert").textContent).toContain("Nenhuma alteração identificada");
  fireEvent.change(screen.getByLabelText("Órgão/Entidade"), { target: { value: "80" } });
  fireEvent.click(screen.getByRole("button", { name: "Aprovar nova versão" }));
  fireEvent.click(screen.getByRole("button", { name: "Confirmar aprovação" }));
  const versoes = JSON.parse(localStorage.getItem(chave)!);
  expect(versoes.map((v: { pesos: number[] }) => v.pesos[0])).toEqual([80, 100]);
  expect(versoes[0].fim).toBeNull();
  expect(versoes[1].fim).toBe(versoes[0].inicio);
  expect(screen.queryByRole("button", { name: "Nova versão a partir de V1" })).toBeNull();
  expect(screen.getByRole("button", { name: "Nova versão a partir de V2" })).toBeTruthy();
  expect(screen.queryByRole("button", { name: "Nova versão" })).toBeNull();
});
it("cancela sem salvar e não sobrescreve dados inválidos", () => {
  localStorage.setItem(chave, "inválido");
  render(<MemoryRouter><PesosAbrangenciasContent /></MemoryRouter>);
  expect(screen.getByRole("alert").textContent).toContain("Não foi possível carregar");
  expect((screen.getByRole("button", { name: "Nova parametrização" }) as HTMLButtonElement).disabled).toBe(true);
  expect(localStorage.getItem(chave)).toBe("inválido");
});
it("valida campos e cancela sem criar uma versão", () => {
  render(<MemoryRouter><PesosAbrangenciasContent /></MemoryRouter>);
  fireEvent.click(screen.getByRole("button", { name: "Nova parametrização" }));
  fireEvent.change(screen.getByLabelText("Órgão/Entidade"), { target: { value: "80" } });
  fireEvent.change(screen.getByLabelText("Carreira"), { target: { value: "101" } });
  fireEvent.click(screen.getByRole("button", { name: "Aprovar parametrização" }));
  expect(screen.getByRole("alert").textContent).toContain("de 0 a 100");
  expect(screen.queryByRole("button", { name: "Confirmar aprovação" })).toBeNull();
  fireEvent.change(screen.getByLabelText("Carreira"), { target: { value: "-1" } });
  fireEvent.click(screen.getByRole("button", { name: "Aprovar parametrização" }));
  expect(screen.getByRole("alert").textContent).toContain("Verifique os pesos informados.");
  expect(screen.queryByRole("button", { name: "Confirmar aprovação" })).toBeNull();
  fireEvent.click(screen.getByRole("button", { name: "Cancelar" }));
  expect(localStorage.getItem(chave)).toBeNull();
  expect(screen.getByRole("button", { name: "Nova parametrização" })).toBeTruthy();
});
it("preserva a versão ativa ao cancelar o versionamento", () => {
  const original = JSON.stringify([{ numero: 2, inicio: "2026-11-16T12:00:00Z", fim: null, pesos: [100, 40, 30, 20, 10, 0] }]);
  localStorage.setItem(chave, original);
  render(<MemoryRouter><PesosAbrangenciasContent /></MemoryRouter>);
  fireEvent.click(screen.getByRole("button", { name: "Nova versão a partir de V2" }));
  expect(screen.queryByRole("region", { name: "Vigência" })).toBeNull();
  expect(document.getElementById("inicio")).toBeNull();
  expect(document.getElementById("fim")).toBeNull();
  expect((screen.getByLabelText("Regime Jurídico") as HTMLInputElement).value).toBe("40");
  fireEvent.change(screen.getByLabelText("Regime Jurídico"), { target: { value: "50" } });
  fireEvent.click(screen.getByRole("button", { name: "Cancelar" }));
  expect(localStorage.getItem(chave)).toBe(original);
  expect(screen.getByRole("cell", { name: "V2" })).toBeTruthy();
});
it("registra as datas automaticamente no versionamento e preserva os dados anteriores", () => {
  localStorage.setItem(chave, JSON.stringify([{ numero: 1, inicio: "2026-11-16T04:00:00Z", fim: null, pesos: [100, 40, 30, 20, 10, 0] }]));
  render(<MemoryRouter><PesosAbrangenciasContent /></MemoryRouter>);
  fireEvent.click(screen.getByRole("button", { name: "Nova versão a partir de V1" }));
  fireEvent.change(screen.getByLabelText("Regime Jurídico"), { target: { value: "60" } });
  fireEvent.click(screen.getByRole("button", { name: "Aprovar nova versão" }));
  const antesDaAprovacao = Date.now();
  fireEvent.click(screen.getByRole("button", { name: "Confirmar aprovação" }));
  const [nova, anterior] = JSON.parse(localStorage.getItem(chave)!);
  expect(new Date(nova.inicio).getTime()).toBeGreaterThanOrEqual(antesDaAprovacao);
  expect(new Date(nova.inicio).getTime()).toBeLessThanOrEqual(Date.now());
  expect(nova.fim).toBeNull();
  expect(nova.pesos[1]).toBe(60);
  expect(anterior.pesos[1]).toBe(40);
  expect(anterior.inicio).toBe("2026-11-16T04:00:00Z");
  expect(anterior.fim).toBe(nova.inicio);
  expect(screen.getByRole("cell", { name: "Ativo" })).toBeTruthy();
});
